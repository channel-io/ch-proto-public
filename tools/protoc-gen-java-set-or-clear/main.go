var logger = log.Default()

func watermark() string {
	return "/* Generated by protoc-gen-java-set-or-clear */\n"
}

var javaTypePrimitiveMappings = map[descriptorpb.FieldDescriptorProto_Type]string{
	descriptorpb.FieldDescriptorProto_TYPE_BOOL:   "java.lang.Boolean",
	descriptorpb.FieldDescriptorProto_TYPE_INT32:  "java.lang.Integer",
	descriptorpb.FieldDescriptorProto_TYPE_INT64:  "java.lang.Long",
	descriptorpb.FieldDescriptorProto_TYPE_UINT32: "java.lang.Integer",
	descriptorpb.FieldDescriptorProto_TYPE_UINT64: "java.lang.Long",
	descriptorpb.FieldDescriptorProto_TYPE_DOUBLE: "java.lang.Double",
	descriptorpb.FieldDescriptorProto_TYPE_FLOAT:  "java.lang.Float",
	descriptorpb.FieldDescriptorProto_TYPE_STRING: "java.lang.String",
}

func extractFromEnumDescriptor(mappings map[string]string, protoPrefix, javaPrefix string, enum *descriptorpb.EnumDescriptorProto) {
	protoTypeName := fmt.Sprintf("%s.%s", protoPrefix, *enum.Name)
	javaTypeName := fmt.Sprintf("%s.%s", javaPrefix, *enum.Name)
	mappings[protoTypeName] = javaTypeName
}

func extractFromMessageDescriptor(mappings map[string]string, protoPrefix, javaPrefix string, message *descriptorpb.DescriptorProto) {
	protoTypeName := fmt.Sprintf("%s.%s", protoPrefix, *message.Name)
	javaTypeName := fmt.Sprintf("%s.%s", javaPrefix, *message.Name)
	mappings[protoTypeName] = javaTypeName

	for _, nestedEnum := range message.EnumType {
		extractFromEnumDescriptor(mappings, protoTypeName, javaTypeName, nestedEnum)
	}
	for _, nestedMessage := range message.NestedType {
		extractFromMessageDescriptor(mappings, protoTypeName, javaTypeName, nestedMessage)
	}
}

func extractProtoTypeToJavaTypeMappings(
	req *plugin.CodeGeneratorRequest,
) (map[string]string, error) {
	javaTypeMappings := map[string]string{}

	for _, protoFile := range req.GetProtoFile() {
		protoPrefix := fmt.Sprintf(".%s", protoFile.GetPackage())
		javaPrefix := protoFile.GetOptions().GetJavaPackage()
		for _, enum := range protoFile.EnumType {
			extractFromEnumDescriptor(javaTypeMappings, protoPrefix, javaPrefix, enum)
		}
		for _, message := range protoFile.MessageType {
			extractFromMessageDescriptor(javaTypeMappings, protoPrefix, javaPrefix, message)
		}
	}

	return javaTypeMappings, nil
}

type MapTypeEntry struct {
	Key   *descriptorpb.FieldDescriptorProto
	Value *descriptorpb.FieldDescriptorProto
}

func extractMapTypeEntryFromMessage(mappings map[string]MapTypeEntry, protoPrefix string, message *descriptorpb.DescriptorProto) {
	protoTypeName := fmt.Sprintf("%s.%s", protoPrefix, *message.Name)

	if strings.HasSuffix(*message.Name, "Entry") {
		entry := MapTypeEntry{}
		for _, field := range message.Field {
			if field.GetName() == "key" {
				entry.Key = field
			} else if field.GetName() == "value" {
				entry.Value = field
			}
		}
		mappings[protoTypeName] = entry
	}

	for _, nestedMessage := range message.NestedType {
		extractMapTypeEntryFromMessage(mappings, protoTypeName, nestedMessage)
	}
}

func extractMapTypeEntries(
	req *plugin.CodeGeneratorRequest,
) (map[string]MapTypeEntry, error) {
	mapTypeEntries := map[string]MapTypeEntry{}

	for _, protoFile := range req.GetProtoFile() {
		protoPrefix := fmt.Sprintf(".%s", protoFile.GetPackage())
		for _, message := range protoFile.MessageType {
			extractMapTypeEntryFromMessage(mapTypeEntries, protoPrefix, message)
		}
	}

	return mapTypeEntries, nil
}

func findMappedJavaType(
	javaTypeMappings map[string]string,
	field *descriptorpb.FieldDescriptorProto,
) (string, error) {
	javaType := ""

	if field.TypeName != nil {
		if field.Label == nil {
			return "", fmt.Errorf("field should have optional or repeated label, but it has no label")
		}

		mappedType, ok := javaTypeMappings[*field.TypeName]
		if !ok {
			return "", fmt.Errorf("unknown type: %s", *field.TypeName)
		}

		if *field.Label == descriptorpb.FieldDescriptorProto_LABEL_OPTIONAL {
			javaType = mappedType
		} else if *field.Label == descriptorpb.FieldDescriptorProto_LABEL_REPEATED {
			javaType = fmt.Sprintf("? extends %s", mappedType)
		} else {
			return "", fmt.Errorf("unsupported label: %s", *field.Label)
		}
	} else if field.Type != nil {
		if mappedType, ok := javaTypePrimitiveMappings[*field.Type]; ok {
			javaType = mappedType
		} else {
			return "", fmt.Errorf("unsupported type: %s", *field.Type)
		}
	}

	return javaType, nil
}

func isMapField(field *descriptorpb.FieldDescriptorProto) bool {
	return field.Label != nil &&
		*field.Label == descriptorpb.FieldDescriptorProto_LABEL_REPEATED &&
		field.Type != nil &&
		*field.Type == descriptorpb.FieldDescriptorProto_TYPE_MESSAGE &&
		field.TypeName != nil &&
		strings.HasSuffix(*field.TypeName, "Entry")
}

// Generates a method that sets or clears an optional field from a nullable value.
//
//	public Builder setOrClearFoo(T value) {
//	  /* ... */
//	}
func generateSetOrClearOptionalField(
	javaType string,
	field *descriptorpb.FieldDescriptorProto,
) (string, error) {
	javaFieldName := strcase.ToCamel(*field.Name)
	return fmt.Sprintf(`
/**
 * @param value The %s to set.
 * @return This builder for chaining.
 */
public Builder setOrClear%s(%s value) {
	if (value == null)
		return clear%s();
	else
		return set%s(value);
}
	`,
		field.GetName(),
		javaFieldName,
		javaType,
		javaFieldName,
		javaFieldName,
	), nil
}

func generateMapOrClearOptionalField(
	javaType string,
	field *descriptorpb.FieldDescriptorProto,
) (string, error) {
	javaFieldName := strcase.ToCamel(*field.Name)
	return fmt.Sprintf(`
/**
 * @param value The value to map.
 * @param mapFunc The function to map the value into the proto message.
 * @return This builder for chaining.
 */
public <T> Builder mapOrClear%s(T value, java.util.function.Function<T, %s> mapFunc) {
	if (value == null)
		return clear%s();
	else
		return set%s(mapFunc.apply(value));
}
	`,
		javaFieldName,
		javaType,
		javaFieldName,
		javaFieldName,
	), nil
}

func generateAddAllOrClearRepeatedField(
	javaType string,
	field *descriptorpb.FieldDescriptorProto,
) (string, error) {
	javaFieldName := strcase.ToCamel(*field.Name)
	return fmt.Sprintf(`
/**
 * @param values The %s to add.
 * @return This builder for chaining.
 */
public Builder addAllOrClear%s(java.lang.Iterable<%s> values) {
	if (values == null)
		return clear%s();
	else
		return addAll%s(values);
}
	`,
		field.GetName(),
		javaFieldName,
		javaType,
		javaFieldName,
		javaFieldName,
	), nil
}

func generateMapAllOrClearRepeatedField(
	javaType string,
	field *descriptorpb.FieldDescriptorProto,
) (string, error) {
	javaFieldName := strcase.ToCamel(*field.Name)
	return fmt.Sprintf(`
/**
 * @param values The values to map.
 * @param mapFunc The function to map the values into each proto message.
 * @return This builder for chaining.
 */
public <T> Builder mapAllOrClear%s(java.lang.Iterable<T> values, java.util.function.Function<T, %s> mapFunc) {
	if (values == null)
		return clear%s();
	else {
		values.forEach(value -> add%s(mapFunc.apply(value)));
		return this;
	}
}
	`,
		javaFieldName,
		javaType,
		javaFieldName,
		javaFieldName,
	), nil
}

func generatePutAllOrClearMapField(
	javaKeyType string,
	javaValueType string,
	field *descriptorpb.FieldDescriptorProto,
) (string, error) {
	javaFieldName := strcase.ToCamel(*field.Name)
	return fmt.Sprintf(`
/**
 * @param map The map to put.
 * @return This builder for chaining.
 */
public Builder putAllOrClear%s(java.util.Map<%s, %s> map) {
	if (map == null)
		return clear%s();
	else
		return putAll%s(map);
}
	`,
		javaFieldName,
		javaKeyType,
		javaValueType,
		javaFieldName,
		javaFieldName,
	), nil
}

func generateForMessage(
	message *descriptorpb.DescriptorProto,
	protoPrefix string,
	javaFilePath string,
	mappings map[string]string,
	mapTypeEntries map[string]MapTypeEntry,
	resp *pluginpb.CodeGeneratorResponse,
) error {
	insertedCode := ""
	insertedCode += watermark()

	protoTypeName := fmt.Sprintf("%s.%s", protoPrefix, *message.Name)

	// skip map entries
	if strings.HasSuffix(*message.Name, "Entry") {
		return nil
	}

	for _, field := range message.GetField() {
		javaType, err := findMappedJavaType(mappings, field)
		if err != nil {
			return err
		}

		if field.Label != nil {
			if *field.Label == descriptorpb.FieldDescriptorProto_LABEL_OPTIONAL {
				if code, err := generateSetOrClearOptionalField(javaType, field); err != nil {
					return err
				} else {
					insertedCode += code
				}

				if code, err := generateMapOrClearOptionalField(javaType, field); err != nil {
					return err
				} else {
					insertedCode += code
				}
			} else if *field.Label == descriptorpb.FieldDescriptorProto_LABEL_REPEATED {
				// should handle map<k, v> separately (they produce different methods in Java)
				if isMapField(field) {
					javaKeyType, err := findMappedJavaType(mappings, mapTypeEntries[*field.TypeName].Key)
					if err != nil {
						return err
					}

					javaValueType, err := findMappedJavaType(mappings, mapTypeEntries[*field.TypeName].Value)
					if err != nil {
						return err
					}

					if code, err := generatePutAllOrClearMapField(javaKeyType, javaValueType, field); err != nil {
						return err
					} else {
						insertedCode += code
					}
				} else {
					if code, err := generateAddAllOrClearRepeatedField(javaType, field); err != nil {
						return err
					} else {
						insertedCode += code
					}

					if code, err := generateMapAllOrClearRepeatedField(javaType, field); err != nil {
						return err
					} else {
						insertedCode += code
					}
				}
			}
		}
	}

	f := &plugin.CodeGeneratorResponse_File{
		Name:           proto.String(javaFilePath),
		InsertionPoint: proto.String(fmt.Sprintf("builder_scope:%s", protoTypeName)),
		Content:        proto.String(insertedCode),
	}

	resp.File = append(resp.File, f)

	// Recurse into nested messages
	for _, nestedMessage := range message.NestedType {
		if err := generateForMessage(nestedMessage, protoTypeName, javaFilePath, mappings, mapTypeEntries, resp); err != nil {
			return err
		}
	}

	return nil
}

func process(
	req *plugin.CodeGeneratorRequest,
	resp *plugin.CodeGeneratorResponse,
) error {
	logger.Println("Applying java-set-or-clear plugin ...")

	resp.SupportedFeatures = proto.Uint64(uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL))

	javaTypeMappings, err := extractProtoTypeToJavaTypeMappings(req)
	if err != nil {
		return err
	}

	mapTypeEntries, err := extractMapTypeEntries(req)
	if err != nil {
		return err
	}

	for _, protoFile := range req.GetProtoFile() {
		if !lo.Contains(req.FileToGenerate, *protoFile.Name) {
			continue
		}

		for _, message := range protoFile.MessageType {
			javaPkgName := protoFile.GetOptions().GetJavaPackage()
			javaFilename := fmt.Sprintf("%s.java", *message.Name)
			javaFilePath := fmt.Sprintf("%s/%s", strings.ReplaceAll(javaPkgName, ".", "/"), javaFilename)

			protoPrefix := protoFile.GetPackage()

			if err := generateForMessage(message, protoPrefix, javaFilePath, javaTypeMappings, mapTypeEntries, resp); err != nil {
				return err
			}
		}
	}

	return nil
}

func main() {
	req := &plugin.CodeGeneratorRequest{}
	resp := &plugin.CodeGeneratorResponse{}

	data, err := io.ReadAll(os.Stdin)
	if err != nil {
		logger.Fatal(err)
		return
	}

	if err := proto.Unmarshal(data, req); err != nil {
		logger.Fatal(err)
		return
	}

	if err := process(req, resp); err != nil {
		logger.Fatal(err)
		return
	}

	out, err := proto.Marshal(resp)
	if err != nil {
		logger.Fatal(err)
		return
	}

	os.Stdout.Write(out)
}
