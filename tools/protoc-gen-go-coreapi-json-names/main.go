package main

import (
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"

	plugin "github.com/golang/protobuf/protoc-gen-go/plugin"
	"github.com/iancoleman/strcase"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

var logger = log.Default()

const outputPath = "coreapi/go/jsonnames/coreapi_json_names.go"

type messageEntry struct {
	fullName string
	fields   []fieldEntry
}

type fieldEntry struct {
	protoName       string
	jsonName        string
	messageFullName string
}

func watermark() string {
	return "// Code generated by protoc-gen-go-coreapi-json-names. DO NOT EDIT.\n\n"
}

func process(req *plugin.CodeGeneratorRequest, resp *plugin.CodeGeneratorResponse) error {
	logger.Println("Applying go-coreapi-json-names plugin ...")

	resp.SupportedFeatures = proto.Uint64(uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL))

	messages := collectMessages(req.GetProtoFile())
	if len(messages) == 0 {
		return nil
	}

	content, err := generateGoFile(messages)
	if err != nil {
		return err
	}

	resp.File = append(resp.File, &plugin.CodeGeneratorResponse_File{
		Name:    proto.String(outputPath),
		Content: proto.String(content),
	})
	return nil
}

func collectMessages(files []*descriptorpb.FileDescriptorProto) map[string]messageEntry {
	descriptors := map[string]*descriptorpb.DescriptorProto{}
	for _, file := range files {
		if !isCoreAPIProtoPackage(file.GetPackage()) {
			continue
		}
		collectMessageDescriptors(descriptors, file.GetPackage(), "", file.GetMessageType())
	}

	messages := map[string]messageEntry{}
	for fullName, message := range descriptors {
		fields := make([]fieldEntry, 0, len(message.GetField()))
		for _, field := range message.GetField() {
			fields = append(fields, fieldEntry{
				protoName:       field.GetName(),
				jsonName:        jsonName(field),
				messageFullName: messageFieldName(field, descriptors),
			})
		}
		messages[fullName] = messageEntry{fullName: fullName, fields: fields}
	}
	return messages
}

func collectMessageDescriptors(
	descriptors map[string]*descriptorpb.DescriptorProto,
	pkg string,
	parent string,
	messages []*descriptorpb.DescriptorProto,
) {
	for _, message := range messages {
		name := message.GetName()
		if parent != "" {
			name = parent + "." + name
		}
		fullName := pkg + "." + name
		descriptors[fullName] = message
		collectMessageDescriptors(descriptors, pkg, name, message.GetNestedType())
	}
}

func isCoreAPIProtoPackage(pkg string) bool {
	return pkg == "coreapi.service" || pkg == "coreapi.model" || pkg == "coreapi.common"
}

func jsonName(field *descriptorpb.FieldDescriptorProto) string {
	if field.GetJsonName() != "" {
		return field.GetJsonName()
	}
	return strcase.ToLowerCamel(field.GetName())
}

func messageFieldName(
	field *descriptorpb.FieldDescriptorProto,
	descriptors map[string]*descriptorpb.DescriptorProto,
) string {
	if field.GetType() != descriptorpb.FieldDescriptorProto_TYPE_MESSAGE {
		return ""
	}

	typeName := strings.TrimPrefix(field.GetTypeName(), ".")
	message, ok := descriptors[typeName]
	if !ok {
		return ""
	}
	if !message.GetOptions().GetMapEntry() {
		return typeName
	}

	for _, nestedField := range message.GetField() {
		if nestedField.GetName() != "value" ||
			nestedField.GetType() != descriptorpb.FieldDescriptorProto_TYPE_MESSAGE {
			continue
		}
		valueTypeName := strings.TrimPrefix(nestedField.GetTypeName(), ".")
		if _, ok := descriptors[valueTypeName]; ok {
			return valueTypeName
		}
	}
	return ""
}

func generateGoFile(messages map[string]messageEntry) (string, error) {
	var b strings.Builder

	b.WriteString(watermark())
	b.WriteString("package jsonnames\n\n")
	b.WriteString("import \"strings\"\n\n")
	b.WriteString("type fieldName struct {\n")
	b.WriteString("\tjsonName string\n")
	b.WriteString("\tmessageFullName string\n")
	b.WriteString("}\n\n")
	b.WriteString("var coreAPIFieldNames = map[string]map[string]fieldName{\n")

	messageNames := make([]string, 0, len(messages))
	for fullName := range messages {
		messageNames = append(messageNames, fullName)
	}
	sort.Strings(messageNames)

	for _, fullName := range messageNames {
		entry := messages[fullName]
		b.WriteString("\t")
		b.WriteString(strconv.Quote(entry.fullName))
		b.WriteString(": {\n")
		for _, field := range entry.fields {
			if field.protoName == "" || field.jsonName == "" {
				return "", fmt.Errorf("message %s has field without proto or JSON name", entry.fullName)
			}
			b.WriteString("\t\t")
			b.WriteString(strconv.Quote(field.protoName))
			b.WriteString(": {jsonName: ")
			b.WriteString(strconv.Quote(field.jsonName))
			if field.messageFullName != "" {
				b.WriteString(", messageFullName: ")
				b.WriteString(strconv.Quote(field.messageFullName))
			}
			b.WriteString("},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString(`func FieldPath(messageFullName, protoPath string) (string, bool) {
	if messageFullName == "" || protoPath == "" {
		return "", false
	}

	fields, ok := coreAPIFieldNames[messageFullName]
	if !ok {
		return "", false
	}

	parts := strings.Split(protoPath, ".")
	jsonParts := make([]string, 0, len(parts))
	for i, part := range parts {
		protoName, suffix := splitIndexedField(part)
		field, ok := fields[protoName]
		if !ok {
			return "", false
		}

		jsonParts = append(jsonParts, field.jsonName+suffix)
		if i == len(parts)-1 {
			return strings.Join(jsonParts, "."), true
		}
		if field.messageFullName == "" {
			return "", false
		}
		fields, ok = coreAPIFieldNames[field.messageFullName]
		if !ok {
			return "", false
		}
	}

	return strings.Join(jsonParts, "."), true
}

func splitIndexedField(segment string) (string, string) {
	index := strings.IndexByte(segment, '[')
	if index < 0 {
		return segment, ""
	}
	return segment[:index], segment[index:]
}
`)

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", err
	}
	return string(formatted), nil
}

func main() {
	req := &plugin.CodeGeneratorRequest{}
	resp := &plugin.CodeGeneratorResponse{}

	data, err := io.ReadAll(os.Stdin)
	if err != nil {
		logger.Fatal(err)
		return
	}

	if err := proto.Unmarshal(data, req); err != nil {
		logger.Fatal(err)
		return
	}

	if err := process(req, resp); err != nil {
		logger.Fatal(err)
		return
	}

	out, err := proto.Marshal(resp)
	if err != nil {
		logger.Fatal(err)
		return
	}

	if _, err := os.Stdout.Write(out); err != nil {
		logger.Fatal(err)
		return
	}
}
