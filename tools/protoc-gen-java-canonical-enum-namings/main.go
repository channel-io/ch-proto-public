package main

import (
	"fmt"
	"io"
	"log"
	"os"
	"strings"

	plugin "github.com/golang/protobuf/protoc-gen-go/plugin"
	"github.com/iancoleman/strcase"
	"github.com/samber/lo"
	"golang.org/x/exp/slices"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

var logger = log.Default()

func watermark() string {
	return "/* Generated by protoc-gen-java-canonical-enum-namings */\n"
}

func extractJavaEnumToProtoEnumMappings(
	protoFile *descriptorpb.FileDescriptorProto,
	enum *descriptorpb.EnumDescriptorProto,
) (string, map[string]string, error) {
	protoEnumNamePrefix := strcase.ToScreamingSnake(*enum.Name) + "_"
	protoEnumUnspecifiedName := fmt.Sprintf("%sUNSPECIFIED", protoEnumNamePrefix)

	if enum.Value[0].Name == nil {
		return "", nil, fmt.Errorf("zero value of enum %s.%s is not specified", *protoFile.Package, *enum.Name)
	}

	if *enum.Value[0].Name != protoEnumUnspecifiedName {
		return "", nil, fmt.Errorf("zero value of enum %s.%s is not %s", *protoFile.Package, *enum.Name, protoEnumUnspecifiedName)
	}

	javaEnumToProtoEnum := map[string]string{}
	for _, value := range enum.Value {
		protoEnumName := *value.Name

		if !strings.HasPrefix(protoEnumName, protoEnumNamePrefix) {
			return "", nil, fmt.Errorf("enum value %s.%s.%s does not follow the best practice", *protoFile.Package, *enum.Name, protoEnumName)
		}

		java_enum_name := strcase.ToLowerCamel(strings.ReplaceAll(protoEnumName, protoEnumNamePrefix, ""))
		if protoEnumName != protoEnumUnspecifiedName {
			javaEnumToProtoEnum[java_enum_name] = protoEnumName
		}
	}

	return protoEnumUnspecifiedName, javaEnumToProtoEnum, nil
}

// Generates a static method that converts a string to an enum.
//
//	public static T forString(String value) {
//	  /* ... */
//	}
func generateJavaConventionalStringToEnum(
	protoFile *descriptorpb.FileDescriptorProto,
	enum *descriptorpb.EnumDescriptorProto,
) (string, error) {
	protoEnumUnspecifiedName, javaEnumToProtoEnum, err := extractJavaEnumToProtoEnumMappings(protoFile, enum)
	if err != nil {
		return "", err
	}

	javaEnumNames := lo.Keys(javaEnumToProtoEnum)
	slices.Sort(javaEnumNames)

	return fmt.Sprintf(`
/**
 * @param value The string value corresponding to the enum entry.
 * @return The enum entry corresponding to the string value.
 */
public static %s forString(String value) {
	switch (value) {
%s
		default: return %s;
	}
}
				`,
		*enum.Name,
		strings.Join(lo.Map(
			javaEnumNames,
			func(javaEnumName string, idx int) string {
				return fmt.Sprintf("    case \"%s\": return %s;", javaEnumName, javaEnumToProtoEnum[javaEnumName])
			},
		), "\n"),
		protoEnumUnspecifiedName,
	), nil
}

// Generates a method that converts an enum to a string.
//
//	public final String getString() {
//	  /* ... */
//	}
func generateEnumToJavaConventionalString(
	protoFile *descriptorpb.FileDescriptorProto,
	enum *descriptorpb.EnumDescriptorProto,
) (string, error) {
	_, javaEnumToProtoEnum, err := extractJavaEnumToProtoEnumMappings(protoFile, enum)
	if err != nil {
		return "", err
	}

	javaEnumNames := lo.Keys(javaEnumToProtoEnum)
	slices.Sort(javaEnumNames)

	return fmt.Sprintf(`
/**
 * @return The string value corresponding to the enum entry.
 */
public final String getString() {
	switch (this) {
%s
		default: return null;
	}
}
				`,
		strings.Join(lo.Map(
			javaEnumNames,
			func(javaEnumName string, idx int) string {
				return fmt.Sprintf("    case %s: return \"%s\";", javaEnumToProtoEnum[javaEnumName], javaEnumName)
			},
		), "\n"),
	), nil
}

func process(
	req *plugin.CodeGeneratorRequest,
	resp *plugin.CodeGeneratorResponse,
) error {
	logger.Println("Applying java-enum-canonical-names plugin ...")

	resp.SupportedFeatures = proto.Uint64(uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL))

	for _, protoFile := range req.GetProtoFile() {
		if !lo.Contains(req.FileToGenerate, *protoFile.Name) {
			continue
		}

		for _, enum := range protoFile.GetEnumType() {
			javaPkgName := protoFile.GetOptions().GetJavaPackage()
			javaFilename := fmt.Sprintf("%s.java", *enum.Name)
			javaFilePath := fmt.Sprintf("%s/%s", strings.ReplaceAll(javaPkgName, ".", "/"), javaFilename)

			insertedCode := ""
			insertedCode += watermark()

			if code, err := generateJavaConventionalStringToEnum(protoFile, enum); err != nil {
				return err
			} else {
				insertedCode += code
			}

			if code, err := generateEnumToJavaConventionalString(protoFile, enum); err != nil {
				return err
			} else {
				insertedCode += code
			}

			f := &plugin.CodeGeneratorResponse_File{
				Name:           proto.String(javaFilePath),
				InsertionPoint: proto.String(fmt.Sprintf("enum_scope:%s.%s", protoFile.GetPackage(), *enum.Name)),
				Content:        proto.String(insertedCode),
			}

			resp.File = append(resp.File, f)
		}
	}

	return nil
}

func main() {
	req := &plugin.CodeGeneratorRequest{}
	resp := &plugin.CodeGeneratorResponse{}

	data, err := io.ReadAll(os.Stdin)
	if err != nil {
		logger.Fatal(err)
		return
	}

	if err := proto.Unmarshal(data, req); err != nil {
		logger.Fatal(err)
		return
	}

	if err := process(req, resp); err != nil {
		logger.Fatal(err)
		return
	}

	out, err := proto.Marshal(resp)
	if err != nil {
		logger.Fatal(err)
		return
	}

	os.Stdout.Write(out)
}
